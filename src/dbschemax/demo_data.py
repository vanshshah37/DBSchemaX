"""Deterministic, synthetic 250-record dataset for the Normalization Lab.

Everything here is **synthetic**: names, e-mail addresses (reserved
``.example`` domain), departments, courses and grades are generated from plain
arithmetic and fixed word lists. No random number generator is involved, so the
output is identical on every run and every Python version. It contains no real
personal data.

The module only builds data. It does not normalize anything and contains no
hard-coded normalization result; the lab feeds the attributes and FDs declared
here to the existing analysis and 3NF-synthesis code.

Shape of the data
-----------------
250 unique enrollment rows over 60 students, 5 departments, 12 courses,
8 instructors and 4 semesters, with the 11 columns listed in
:data:`DEMO_ATTRIBUTES` and the dependencies in :data:`DEMO_FD_TEXT`.
"""

from __future__ import annotations

from dataclasses import dataclass

from dbschemax.inputs import parse_fd_items
from dbschemax.models import FunctionalDependency

DEMO_TITLE = "Synthetic university enrollments (250 records)"
SYNTHETIC_NOTICE = (
    "SYNTHETIC DATA — generated by DBSchemaX from fixed word lists and arithmetic. "
    "Names, e-mail addresses and grades are invented and do not describe real people."
)

DEMO_ATTRIBUTES: tuple[str, ...] = (
    "StudentID",
    "StudentName",
    "StudentEmail",
    "DeptID",
    "DeptName",
    "CourseID",
    "CourseName",
    "Semester",
    "InstructorID",
    "InstructorName",
    "Grade",
)

DEMO_FD_TEXT: tuple[str, ...] = (
    "StudentID -> StudentName, StudentEmail, DeptID",
    "DeptID -> DeptName",
    "CourseID -> CourseName",
    "InstructorID -> InstructorName",
    "CourseID, Semester -> InstructorID",
    "StudentID, CourseID, Semester -> Grade",
)

DEMO_CANDIDATE_KEY: frozenset[str] = frozenset({"StudentID", "CourseID", "Semester"})

# Expected sizes (also enforced when the dataset is built).
ROW_COUNT = 250
STUDENT_COUNT = 60
DEPARTMENT_COUNT = 5
COURSE_COUNT = 12
INSTRUCTOR_COUNT = 8
SEMESTER_COUNT = 4

_DEPARTMENTS = (
    "Computer Science",
    "Mathematics",
    "Physics",
    "Electrical Engineering",
    "Mechanical Engineering",
)
_COURSES = (
    "Programming Fundamentals",
    "Discrete Mathematics",
    "Data Structures",
    "Database Systems",
    "Linear Algebra",
    "Probability and Statistics",
    "Classical Mechanics",
    "Digital Logic Design",
    "Signals and Systems",
    "Thermodynamics",
    "Computer Networks",
    "Numerical Methods",
)
_SEMESTERS = ("2025-Fall", "2026-Spring", "2026-Fall", "2027-Spring")
_FIRST_NAMES = (
    "Aarav", "Bianca", "Chen", "Dmitri", "Elena", "Farid",
    "Grace", "Hiro", "Isla", "Jamal", "Kavya", "Liam",
)  # 12 names
_LAST_NAMES = ("Ahmed", "Brooks", "Castillo", "Duarte", "Evans")  # 5 names
_INSTRUCTOR_NAMES = (
    "Prof. Alder", "Prof. Bhatt", "Prof. Costa", "Prof. Dube",
    "Prof. Eriksen", "Prof. Fontaine", "Prof. Gupta", "Prof. Haddad",
)
_GRADES = ("A", "A-", "B+", "B", "B-", "C+", "C")

# Presentation labels for the demo's output relations, keyed by the relation's
# primary key. They only name tables the synthesis has already produced; the
# lab falls back to a generic name for any schema not listed here.
RELATION_LABELS: dict[frozenset[str], tuple[str, str]] = {
    frozenset({"StudentID"}): (
        "Student", "One row per student: name, e-mail and home department."),
    frozenset({"DeptID"}): (
        "Department", "One row per department: its name."),
    frozenset({"CourseID"}): (
        "Course", "One row per course: its title."),
    frozenset({"InstructorID"}): (
        "Instructor", "One row per instructor: their name."),
    frozenset({"CourseID", "Semester"}): (
        "CourseOffering", "One row per course offered in a semester, with who teaches it."),
    frozenset({"StudentID", "CourseID", "Semester"}): (
        "Enrollment", "One row per student taking a course in a semester, with the grade."),
}


@dataclass(frozen=True)
class DemoDataset:
    """A relation instance plus everything the lab needs to analyze it."""

    title: str
    notice: str
    relation_name: str
    attributes: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]
    fd_text: tuple[str, ...]
    declared_key: frozenset[str]
    non_atomic: tuple[str, ...]
    labels: dict[frozenset[str], tuple[str, str]]

    @property
    def fds(self) -> tuple[FunctionalDependency, ...]:
        """The declared FDs, parsed by the project's real FD parser."""
        return parse_fd_items(self.fd_text)

    def column(self, name: str) -> tuple[str, ...]:
        index = self.attributes.index(name)
        return tuple(row[index] for row in self.rows)


def _student_rows() -> list[dict[str, str]]:
    students = []
    for i in range(STUDENT_COUNT):
        # 12 and 5 are coprime, so all 60 (first, last) pairs are distinct.
        first, last = _FIRST_NAMES[i % 12], _LAST_NAMES[i % 5]
        students.append(
            {
                "StudentID": f"S{i + 1:03d}",
                "StudentName": f"{first} {last}",
                "StudentEmail": f"student{i + 1:03d}@demo.example",
                "DeptID": f"D{i % DEPARTMENT_COUNT + 1:02d}",
            }
        )
    return students


def _instructor_for(course_index: int, semester_index: int) -> int:
    """Deterministic teaching assignment: one instructor per (course, semester)."""
    return (3 * course_index + semester_index) % INSTRUCTOR_COUNT


def build_demo_dataset() -> DemoDataset:
    """Build the 250-record dataset. Pure and deterministic.

    Raises:
        AssertionError: if the generator's own size/uniqueness guarantees fail
            (a bug in this module, not a user error).
    """
    students = _student_rows()
    dept_names = {f"D{i + 1:02d}": name for i, name in enumerate(_DEPARTMENTS)}

    rows: list[tuple[str, ...]] = []
    seen: set[tuple[int, int, int]] = set()
    for s in range(STUDENT_COUNT):
        enrollments = 4 + (1 if s < 10 else 0)  # 60 * 4 + 10 = 250
        for k in range(enrollments):
            semester = (s + k) % SEMESTER_COUNT
            course = (5 * s + 7 * k + s // 12) % COURSE_COUNT
            while (s, course, semester) in seen:  # keep the composite key unique
                course = (course + 1) % COURSE_COUNT
            seen.add((s, course, semester))
            instructor = _instructor_for(course, semester)
            student = students[s]
            rows.append(
                (
                    student["StudentID"],
                    student["StudentName"],
                    student["StudentEmail"],
                    student["DeptID"],
                    dept_names[student["DeptID"]],
                    f"C{101 + course}",
                    _COURSES[course],
                    _SEMESTERS[semester],
                    f"I{instructor + 1:02d}",
                    _INSTRUCTOR_NAMES[instructor],
                    _GRADES[(7 * s + 3 * course + 5 * semester + k) % len(_GRADES)],
                )
            )
    assert len(rows) == ROW_COUNT and len(set(rows)) == ROW_COUNT
    return DemoDataset(
        title=DEMO_TITLE,
        notice=SYNTHETIC_NOTICE,
        relation_name="Enrollment_Raw",
        attributes=DEMO_ATTRIBUTES,
        rows=tuple(rows),
        fd_text=DEMO_FD_TEXT,
        declared_key=DEMO_CANDIDATE_KEY,
        non_atomic=(),  # every value is a single, indivisible value
        labels=dict(RELATION_LABELS),
    )


_LIST_SEPARATORS = (",", ";", "|", "\n")


def atomicity_problems(dataset: DemoDataset) -> list[str]:
    """Report cells that are empty or look like packed lists (1NF sanity check).

    This is a heuristic for the generated data: every cell must be a non-empty
    string containing no list separator. An empty result means "no problems".
    """
    problems = []
    for number, row in enumerate(dataset.rows, start=1):
        if len(row) != len(dataset.attributes):
            problems.append(f"row {number} has {len(row)} values, expected {len(dataset.attributes)}")
            continue
        for name, value in zip(dataset.attributes, row):
            if not isinstance(value, str) or not value.strip():
                problems.append(f"row {number}, {name}: empty or non-text value")
            elif any(sep in value for sep in _LIST_SEPARATORS):
                problems.append(f"row {number}, {name}: contains a list separator: {value!r}")
    return problems
